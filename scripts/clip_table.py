"""Writes a baked clip table into pose.rs and regenerates the clip registry (AN-02-S12):
scripts/clip_table.py <rows> <NAME> <doc> <field,...> [--smooth] [--center field,...]

<rows> is examples/fit_clip output (one sample per line, all fields in its order). The chosen fields become
`pub const <NAME>: [[f32; F]; N]` in pose.rs, between `// CLIP <NAME> BEGIN` and `// CLIP <NAME> END`
(replaced when present, else appended). The tables live only in pose.rs: the registry blocks (`// CLIP
REGISTRY`) in pose.rs and common.wgsl are rebuilt from every table found, giving each its offset in the GPU clip
buffer (`clip_buffer`, uploaded once; the shader reads it with `clip_pos`/`clip_get`). The CPU samples a
table with `clip_at`. `--center` stores those fields as motion around their loop average (the pose keeps its
own value and adds the clip's swing). `--smooth` runs one circular [1, 2, 1] / 4 pass over the loop to settle fit jitter."""
import re, sys
FIELDS = "hipL hipR kneeL kneeR sideL sideR lean twist tilt head look shL shR elL elR reachL reachR abL abR bob yaw".split()
RS, WG = "crates/scalia-render/src/pose.rs", "crates/scalia-render/src/wgsl/common.wgsl"

def replace(path, begin, end, block):
    s = open(path).read()
    pat = re.compile(re.escape(begin) + ".*?" + re.escape(end) + "\n", re.S)
    s = pat.sub(lambda _: block, s) if pat.search(s) else s.rstrip("\n") + "\n\n" + block
    open(path, "w").write(s)

def write_table(rows_path, name, doc, fields, smooth, center=()):
    cols = [FIELDS.index(f) for f in fields]
    rows = [[float(l.split()[c]) for c in cols] for l in open(rows_path) if l.strip()]
    n, f = len(rows), len(fields)
    for k, fld in enumerate(fields):
        if fld in center:
            m = sum(r[k] for r in rows) / n
            for r in rows: r[k] -= m
    if smooth:
        rows = [[(rows[i-1][k] + 2*rows[i][k] + rows[(i+1) % n][k]) / 4 for k in range(f)] for i in range(n)]
    body = "".join("    [" + ", ".join(f"{v:.4f}" for v in r) + "],\n" for r in rows)
    replace(RS, f"// CLIP {name} BEGIN", f"// CLIP {name} END",
            f"// CLIP {name} BEGIN\n/// {doc} Generated by scripts/clip_table.py: {n} samples over one loop;\n"
            f"/// fields: {', '.join(fields)}.\npub const {name}: [[f32; {f}]; {n}] = [\n{body}];\n// CLIP {name} END\n")
    print(f"{name}: {n} x {f} written")

def registry():
    s = open(RS).read()
    tables = re.findall(r"// CLIP (\w+) BEGIN.*?pub const \1: \[\[f32; (\d+)\]; (\d+)\]", s, re.S)
    tables = [(nm, int(f), int(n)) for nm, f, n in tables if nm != "REGISTRY"]
    at, rs, wg = 0, [], []
    for nm, f, n in tables:
        rs.append(f"pub const {nm}_AT: u32 = {at};")
        wg.append(f"const {nm}_AT: u32 = {at}u;\nconst {nm}_F: u32 = {f}u;\nconst {nm}_N: u32 = {n}u;")
        at += f * n
    ext = "".join(f"    v.extend({nm}.iter().flatten());\n" for nm, _, _ in tables)
    replace(RS, "// CLIP REGISTRY BEGIN", "// CLIP REGISTRY END",
            "// CLIP REGISTRY BEGIN\n// Generated by scripts/clip_table.py from the tables above: each table's offset in the GPU clip buffer.\n"
            + "\n".join(rs) + f"\n/// Floats in the clip buffer.\npub const CLIP_FLOATS: u32 = {at};\n"
            "/// Every baked clip table back to back, rows in order (uploaded once; common.wgsl reads it as `clips`).\n"
            f"pub fn clip_buffer() -> Vec<f32> {{\n    let mut v = Vec::with_capacity({at});\n{ext}    v\n}}\n// CLIP REGISTRY END\n")
    replace(WG, "// CLIP REGISTRY BEGIN", "// CLIP REGISTRY END",
            "// CLIP REGISTRY BEGIN\n// Generated by scripts/clip_table.py: baked clip tables (pose.rs `clip_buffer`), read-only on the GPU.\n"
            "@group(0) @binding(3) var<storage, read> clips: array<f32>;\n" + "\n".join(wg) + "\n"
            "// Where a loop of `n` rows of `f` fields at `at` is at `phase`: the two rows around it and the weight.\n"
            "struct ClipPos { a: u32, b: u32, w: f32 }\n"
            "fn clip_pos(at: u32, f: u32, n: u32, phase: f32) -> ClipPos {\n"
            "  let x = fract(phase) * f32(n);\n  let i0 = u32(floor(x)) % n;\n"
            "  return ClipPos(at + i0 * f, at + ((i0 + 1u) % n) * f, x - floor(x));\n}\n"
            "fn clip_get(c: ClipPos, k: u32) -> f32 { return mix(clips[c.a + k], clips[c.b + k], c.w); }\n// CLIP REGISTRY END\n")
    print(f"registry: {len(tables)} tables, {at} floats")

if __name__ == "__main__":
    a = sys.argv[1:]
    if a and a[0] != "--registry":
        center = a[a.index("--center") + 1].split(",") if "--center" in a else ()
        write_table(a[0], a[1], a[2], a[3].split(","), "--smooth" in a, center)
    registry()
