"""Writes a baked clip table into pose.rs and its mirror into common.wgsl (AN-02-S12):
scripts/clip_table.py <rows> <NAME> <doc> <field,...> [--smooth]

<rows> is examples/fit_clip output (one sample per line, all fields in CLIP_FIELDS order). The chosen fields
become `pub const <NAME>: [[f32; F]; N]` in pose.rs (sample it with `clip_at`) and `fn <name>(phase)` in
common.wgsl, each between `// CLIP <NAME> BEGIN` and `// CLIP <NAME> END` (replaced when present, else
appended to the file). `--smooth` runs one circular [1, 2, 1] / 4 pass over the loop to settle fit jitter."""
import re, sys
FIELDS = "hipL hipR kneeL kneeR sideL sideR lean twist tilt head look shL shR elL elR reachL reachR abL abR bob".split()
rows_path, name, doc, fields = sys.argv[1:5]; smooth = '--smooth' in sys.argv
fields = fields.split(','); cols = [FIELDS.index(f) for f in fields]
rows = [[float(l.split()[c]) for c in cols] for l in open(rows_path) if l.strip()]
n, f = len(rows), len(fields)
if smooth:
    rows = [[(rows[i-1][k] + 2*rows[i][k] + rows[(i+1) % n][k]) / 4 for k in range(f)] for i in range(n)]
fmt = lambda r: ", ".join(f"{v:.4f}" for v in r)
begin, end = f"// CLIP {name} BEGIN", f"// CLIP {name} END"
rs = (f"{begin}\n/// {doc} Generated by scripts/clip_table.py: {n} samples over one loop (sample with `clip_at`),\n"
      f"/// fields: {', '.join(fields)}.\npub const {name}: [[f32; {f}]; {n}] = [\n"
      + "".join(f"    [{fmt(r)}],\n" for r in rows) + f"];\n{end}\n")
lower = name.lower()
wg = (f"{begin}\n// {doc} Mirrors {name} in pose.rs (scripts/clip_table.py); fields: {', '.join(fields)}.\n"
      f"fn {lower}(phase: f32) -> array<f32, {f}> {{\n  let t = array<array<f32, {f}>, {n}>(\n"
      + ",\n".join(f"    array<f32, {f}>({fmt(r)})" for r in rows)
      + f"\n  );\n  let x = fract(phase) * {n}.0;\n  let i0 = u32(floor(x)) % {n}u;\n  let i1 = (i0 + 1u) % {n}u;\n"
      f"  let w = x - floor(x);\n  var o: array<f32, {f}>;\n  for (var k = 0u; k < {f}u; k++) {{ o[k] = mix(t[i0][k], t[i1][k], w); }}\n"
      f"  return o;\n}}\n{end}\n")
for path, block in (("crates/scalia-render/src/pose.rs", rs), ("crates/scalia-render/src/wgsl/common.wgsl", wg)):
    s = open(path).read()
    pat = re.compile(re.escape(begin) + ".*?" + re.escape(end) + "\n", re.S)
    s = pat.sub(lambda _: block, s) if pat.search(s) else s.rstrip("\n") + "\n\n" + block
    open(path, "w").write(s)
print(f"{name}: {n} x {f} written")
